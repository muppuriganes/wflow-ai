import uuid
from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, Field, StringConstraints

from app.schemas.common import APIModel

DisplayName = Annotated[str, StringConstraints(strip_whitespace=True, min_length=2, max_length=100)]


class ConnectionCreate(BaseModel):
    display_name: DisplayName
    channel_type: Literal["whatsapp_web", "simulator"] = "whatsapp_web"


class ConnectionOut(APIModel):
    id: uuid.UUID
    channel_type: str
    display_name: str
    phone_number: str | None
    account_name: str | None
    status: str
    status_detail: str | None
    last_connected_at: datetime | None
    last_disconnected_at: datetime | None
    created_at: datetime
    updated_at: datetime


class QRCodeOut(BaseModel):
    status: str
    qr_data_url: str | None
    expires_in: int | None


class ConnectionEventOut(APIModel):
    id: uuid.UUID
    event_type: str
    summary: str | None
    details: dict[str, Any]
    occurred_at: datetime


class ChannelCapabilities(BaseModel):
    channel_types: list[str]
    max_connections: int
    send_limit_per_minute: int


class SimulateScan(BaseModel):
    pass


class SimulateInbound(BaseModel):
    phone: Annotated[str, StringConstraints(pattern=r"^\+?\d{6,15}$")]
    name: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=100)]
    text: Annotated[str, StringConstraints(min_length=1, max_length=4096)]


class ContactSummary(APIModel):
    id: uuid.UUID
    display_name: str | None
    phone_number: str | None
    external_id: str
    consent_status: str
    opted_out_at: datetime | None


class ConversationOut(BaseModel):
    id: uuid.UUID
    connection_id: uuid.UUID
    contact: ContactSummary
    is_group: bool
    status: str
    last_message_at: datetime | None
    last_message_preview: str | None
    unread_count: int


class MessageOut(APIModel):
    id: uuid.UUID
    conversation_id: uuid.UUID
    direction: str
    message_type: str
    content: str | None
    status: str
    error: str | None
    sent_by_user_id: uuid.UUID | None
    created_at: datetime
    status_updated_at: datetime | None


class SendMessage(BaseModel):
    text: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=4096)]
    # Idempotency key generated by the client; retries with the same key never send twice.
    client_message_id: str = Field(min_length=8, max_length=64, pattern=r"^[A-Za-z0-9_\-]+$")


class RestoreItem(BaseModel):
    connection_id: uuid.UUID
    organization_id: uuid.UUID
    channel_type: str
